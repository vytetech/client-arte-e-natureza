const DICTS: Record<Lang, Dict> = { pt, en, es, ar };

const STORAGE_KEY = "atelier-lang";

type LangCtx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
  enabled: Lang[];
};

const Ctx = createContext<LangCtx>({
  lang: "pt",
  setLang: () => {},
  t: (k) => pt[k] ?? k,
  enabled: ["pt", "en", "es", "ar"],
});

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const { settings } = useSettings();
  const [lang, setLangState] = useState<Lang>(() => {
    const v = typeof window !== "undefined" ? window.localStorage.getItem(STORAGE_KEY) : null;
    return v === "en" || v === "es" || v === "ar" ? v : "pt";
  });

  // Português é sempre ativo e é o idioma padrão; os demais podem ser ligados/desligados no admin
  const enabled: Lang[] = (["pt", "en", "es", "ar"] as Lang[]).filter(
    (l) => l === "pt" || (settings[`lang.${l}`] ?? "1") !== "0"
  );

  const effective: Lang = enabled.includes(lang) ? lang : "pt";

  useEffect(() => {
    document.documentElement.lang = effective === "pt" ? "pt-BR" : effective;
    document.documentElement.dir = LANG_META[effective].rtl ? "rtl" : "ltr";
  }, [effective]);

  const setLang = (l: Lang) => {
    window.localStorage.setItem(STORAGE_KEY, l);
    setLangState(l);
  };

  const t = (key: string) => DICTS[effective][key] ?? pt[key] ?? key;

  return <Ctx.Provider value={{ lang: effective, setLang, t, enabled }}>{children}</Ctx.Provider>;
}

export function useLang() {
  return useContext(Ctx);
}
